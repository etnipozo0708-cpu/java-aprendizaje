public class VariablesYTipos {
    public static void main(String[] args) {
        // Variables de tipo entero
        int edad = 25;
        int año = 2026;
        
        // Variables de tipo decimal
        double precio = 19.99;
        double estatura = 1.75;
        
        // Variables de texto
        String nombre = "Etni";
        String ciudad = "México";
        
        // Variables booleanas (verdadero/falso)
        boolean esEstudiante = true;
        boolean tieneTrabajo = false;
        
        // Variable de un solo carácter
        char inicial = 'E';
        
        // Imprimimos los valores
        System.out.println("Nombre: " + nombre);
        System.out.println("Edad: " + edad);
        System.out.println("Año: " + año);
        System.out.println("Precio: " + precio);
        System.out.println("Estatura: " + estatura);
        System.out.println("Ciudad: " + ciudad);
        System.out.println("¿Es estudiante? " + esEstudiante);
        System.out.println("¿Tiene trabajo? " + tieneTrabajo);
        System.out.println("Inicial: " + inicial);
    }
}